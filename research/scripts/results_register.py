"""Write docs/research/results.md, the results register, from the MANIFEST and the results files.

Usage: python research/scripts/results_register.py --config research/configs/results-register.json
       --out docs/research/results.md [--check]

One section per MANIFEST row, grouped by hypothesis. The config gives each row's
question, status, hypothesis, pre-registration section and the JSON paths of its
headline values; the script reads every value from the committed results file,
the config, script, commit and sha256 from the MANIFEST, and the log entries
from docs/log, so no number in the register is typed (AGENTS.md rule 9). It
refuses a MANIFEST row without a section or a section without a row, a file
whose sha256 differs from its row, a path that does not resolve to one scalar,
a pre-registration heading the pre-registration does not hold, and a row no
current measurement entry records. With --check it writes nothing and fails
when the committed register differs from what it would write.

Only measurement entries are read from docs/log, so the register goes stale
when a measurement entry citing a MANIFEST row is added or superseded, or when
the MANIFEST, a results file or the config changes; a finding, decision or
change entry citing a results file leaves it current.

The first PR that commits a hypothesis result (H1's table, card X4, the first)
must do three things, or this script refuses it: add the row's section to the
config; add a status for a hypothesis result to STATUSES and to
HYPOTHESIS_RESULTS, so that the generated top paragraph names the result
instead of saying no hypothesis has one; and rewrite the config's dated intro
paragraph about H1's live runs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path
from typing import Any

from scripts.consolidate_log import MANIFEST, Entry, load_entries

REPO = Path(__file__).resolve().parents[2]
PREREG = "docs/research/preregistration.md"
STATUSES = {
    "support artefact": "an input a registered analysis uses (a list, a draw, a mapping), "
    "not a measurement of any hypothesis",
    "fixture-size measurement": "a measurement on a fixed corpus or fixture, model-free or "
    "on a scripted model, not on a live model",
    "reach measurement": "what the plane lets a reader reach on a benchmark's own data, "
    "with no model called",
    "cost estimate": "dollars and calls estimated from token counts and prices; no model called",
    "power computation": "a simulation of the registered test that sets or checks a sample size",
    "engineering check": "a check of a component's behaviour or speed that decides no hypothesis",
    "proof of concept": "a reproducible demonstration that the system works as built, on "
    "fixtures, the code's own tests or scripted models, never a hypothesis result",
}
# The statuses that are a test of a hypothesis. None yet: no MANIFEST row decides H1 to H5.
HYPOTHESIS_RESULTS: frozenset[str] = frozenset()
HEADER = (
    "Generated by `research/scripts/results_register.py` from "
    "`research/configs/results-register.json`, `research/results/MANIFEST.md`, the results "
    "files and the measurement entries in `docs/log`; run `make results-register` after any "
    "of them changes. "
    "Edit the config, not this file."
)


class RegisterError(Exception):
    def __init__(self, problems: list[str]) -> None:
        super().__init__("\n".join(problems))
        self.problems = problems


@dataclass(frozen=True)
class Row:
    file: str
    config: str
    script: str
    commit: str
    sha256: str


def load_manifest_rows(root: Path) -> dict[str, Row]:
    rows: dict[str, Row] = {}
    for line in (root / MANIFEST).read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 6 and cells[0].startswith("research/results/"):
            rows[cells[0]] = Row(cells[0], cells[1], cells[2], cells[3], cells[4])
    return rows


def resolve(data: Any, path: Sequence[Any]) -> Any:
    """Follow a path of keys, list indexes and selectors to one scalar.

    A selector is an object: it picks the one element of a list whose fields
    equal all of the selector's, so a path names a cell by what it is.
    """
    value = data
    for segment in path:
        if isinstance(segment, dict):
            if not isinstance(value, list):
                raise ValueError(f"selector {json.dumps(segment)} applied to a non-list")
            found = [
                v
                for v in value
                if isinstance(v, dict) and all(k in v and v[k] == s for k, s in segment.items())
            ]
            if len(found) != 1:
                raise ValueError(f"selector {json.dumps(segment)} matches {len(found)} elements")
            value = found[0]
        elif isinstance(segment, bool):
            raise ValueError("a path segment is a key, an index or a selector")
        elif isinstance(segment, int):
            if not isinstance(value, list) or not -len(value) <= segment < len(value):
                raise ValueError(f"index {segment} out of range")
            value = value[segment]
        elif isinstance(segment, str):
            if not isinstance(value, dict) or segment not in value:
                raise ValueError(f"key {segment!r} not found")
            value = value[segment]
        else:
            raise ValueError("a path segment is a key, an index or a selector")
    if isinstance(value, dict | list):
        raise ValueError("path ends at an object or a list, not a scalar")
    return value


def path_text(path: Sequence[Any]) -> str:
    parts: list[str] = []
    for segment in path:
        if isinstance(segment, dict):
            inner = ", ".join(f"{k}={json.dumps(v)}" for k, v in segment.items())
            parts.append(f"[{inner}]")
        elif isinstance(segment, int):
            parts.append(f"[{segment}]")
        else:
            parts.append(("." if parts else "") + str(segment))
    return "".join(parts)


def _commas(digits: str) -> str:
    sign = "-" if digits.startswith("-") else ""
    digits = digits.lstrip("-")
    groups: list[str] = []
    while len(digits) > 3:
        groups.insert(0, digits[-3:])
        digits = digits[:-3]
    groups.insert(0, digits)
    return sign + ",".join(groups)


def value_text(value: Any) -> str:
    """A value with thousands separated and floats in positional notation, as the file holds them.

    Python's repr writes 0.000031 as 3.1e-05; the results file and the register write 0.000031.
    """
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return _commas(str(value))
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            return repr(value)
        text = format(Decimal(repr(value)), "f")
        if "." not in text:
            text += ".0"
        whole, _, fraction = text.partition(".")
        return f"{_commas(whole)}.{fraction}"
    return f"`{value}`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _headings(root: Path) -> set[str]:
    lines = (root / PREREG).read_text(encoding="utf-8").splitlines()
    return {line.strip() for line in lines if line.startswith("#")}


def _cites(e: Entry, file: str) -> bool:
    return file in e.evidence


def _standing(results: Sequence[Mapping[str, Any]], counts: Mapping[str, int]) -> str:
    """The top paragraph: whether any hypothesis has a result, from the statuses alone."""
    decided = [r for r in results if r["status"] in HYPOTHESIS_RESULTS]
    present = [s for s in STATUSES if counts[s] and s not in HYPOTHESIS_RESULTS]
    kinds = " or ".join(filter(None, [", ".join(present[:-1]), present[-1] if present else ""]))
    if not decided:
        return (
            "**No hypothesis has a result yet.** Every committed file is a "
            f"{kinds}. None is a test of H1 to H5, and none may be quoted as one."
        )
    names = ", ".join(f"`{r['file']}` ({r['hypothesis']})" for r in decided)
    return f"**Hypothesis results:** {names}. Every other committed file is a {kinds}."


def build(root: Path, config: Mapping[str, Any]) -> str:
    rows = load_manifest_rows(root)
    entries, problems = load_entries(root)
    superseded = {e.get("supersedes") for e in entries}
    current = sorted(
        (e for e in entries if e.path not in superseded and e.get("type") == "measurement"),
        key=Entry.sort_key,
    )
    headings = _headings(root)
    groups: list[dict[str, Any]] = list(config["groups"])
    group_ids = [g["id"] for g in groups]
    results: list[dict[str, Any]] = list(config["results"])

    named = [r["file"] for r in results]
    problems += [f"{f}: MANIFEST row has no section in the config" for f in rows if f not in named]
    problems += [f"{f}: section has no MANIFEST row" for f in named if f not in rows]
    problems += [f"{f}: more than one section" for f in set(named) if named.count(f) > 1]

    rendered: dict[str, list[str]] = {g: [] for g in group_ids}
    counts: dict[str, int] = dict.fromkeys(STATUSES, 0)
    for r in results:
        file = r["file"]
        if file not in rows:
            continue
        row = rows[file]
        if r["status"] not in STATUSES:
            problems.append(f"{file}: status {r['status']!r} is not one of {', '.join(STATUSES)}")
            continue
        if r["hypothesis"] not in group_ids:
            problems.append(f"{file}: hypothesis {r['hypothesis']!r} is not a group")
            continue
        prereg = r.get("prereg")
        if prereg is not None and prereg not in headings:
            problems.append(f"{file}: {PREREG} has no heading {prereg!r}")
        raw = (root / file).read_bytes()
        if hashlib.sha256(raw).hexdigest() != row.sha256:
            problems.append(f"{file}: sha256 does not match MANIFEST.md")
        data = json.loads(raw.decode("utf-8"))
        table = ["| value | reads | key path |", "|---|---|---|"]
        for h in r["headline"]:
            try:
                value = resolve(data, h["path"])
            except ValueError as e:
                problems.append(f"{file}: {path_text(h['path'])}: {e}")
                continue
            table.append(
                f"| {_cell(h['label'])} | {_cell(value_text(value))} "
                f"| `{_cell(path_text(h['path']))}` |"
            )
        measurements = [e for e in current if _cites(e, file)]
        if not measurements:
            problems.append(f"{file}: no current measurement entry in docs/log cites it")
        counts[r["status"]] += 1
        title = prereg.lstrip("# ") if prereg is not None else None
        serves = f'pre-registration section "{title}"' if title else "no pre-registration section"
        lines = [
            f"### `{file}`",
            "",
            f"- **Question.** {r['question']}",
            f"- **Status.** {r['status']}: {STATUSES[r['status']]}.",
            f"- **Serves.** {r['hypothesis'] if r['hypothesis'] != 'none' else 'no hypothesis'}; "
            f"{serves}." + (f" {r['note']}" if r.get("note") else ""),
            f"- **Made by.** `{row.script}` from `{row.config}`, MANIFEST commit `{row.commit}`, "
            f"sha256 `{row.sha256}`.",
            "",
            *table,
            "",
            "Recorded by "
            + ", ".join(f"[`{e.path}`](../log/{e.path.split('/')[-1]})" for e in measurements)
            + ".",
            "",
        ]
        rendered[r["hypothesis"]].extend(lines)
    if problems:
        raise RegisterError(problems)

    out = [f"# {config['title']}", "", HEADER, "", config["intro"][0], ""]
    out += [_standing(results, counts), ""]
    for paragraph in config["intro"][1:]:
        out += [paragraph, ""]
    out += ["| status | results | what it is |", "|---|---|---|"]
    out += [f"| {s} | {counts[s]} | {STATUSES[s]} |" for s in STATUSES]
    out += ["", f"{sum(counts.values())} results in all, one per MANIFEST row.", ""]
    out += ["## What each hypothesis still needs", ""]
    for g in groups:
        if "needs" in g:
            out.append(f"- **{g['title']}.** {g['needs']}")
    out.append("")
    for g in groups:
        if rendered[g["id"]]:
            out += [f"## {g['title']}", "", *rendered[g["id"]]]
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0] if __doc__ else None)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--root", type=Path, default=REPO)
    parser.add_argument("--check", action="store_true", help="fail if --out is not current")
    args = parser.parse_args(argv)
    config = json.loads(args.config.read_text(encoding="utf-8"))
    try:
        text = build(args.root, config)
    except RegisterError as e:
        for problem in e.problems:
            print(problem, file=sys.stderr)
        return 1
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out.as_posix()} is stale: run make results-register", file=sys.stderr)
            return 1
        print(f"{args.out.as_posix()} is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {args.out.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
