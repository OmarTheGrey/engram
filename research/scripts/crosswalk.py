def string_at(text: str, i: int) -> tuple[str, int] | None:
    """The JavaScript string literal starting at text[i] and the index after it, or None.

    A template literal with a `${` substitution is not a constant and gives None.
    """
    if i >= len(text) or text[i] not in "\"'`":
        return None
    quote = text[i]
    out: list[str] = []
    j = i + 1
    while j < len(text):
        c = text[j]
        if c == "\\":
            if j + 1 >= len(text):
                return None
            nxt = text[j + 1]
            if nxt == "\n":
                j += 2
                continue
            if nxt == "u" and text[j + 2 : j + 3] == "{":
                end = text.find("}", j + 3)
                if end < 0:
                    return None
                out.append(chr(int(text[j + 3 : end], 16)))
                j = end + 1
                continue
            if nxt == "u":
                out.append(chr(int(text[j + 2 : j + 6], 16)))
                j += 6
                continue
            if nxt == "x":
                out.append(chr(int(text[j + 2 : j + 4], 16)))
                j += 4
                continue
            out.append(_ESCAPES.get(nxt, nxt))
            j += 2
            continue
        if quote == "`" and c == "$" and text[j + 1 : j + 2] == "{":
            return None
        if c == quote:
            return "".join(out), j + 1
        if c == "\n" and quote != "`":
            return None
        out.append(c)
        j += 1
    return None


class Unparsed(ValueError):
    """A file the scanner cannot read as code: an unterminated string, comment or bracket."""


@dataclass(frozen=True)
class Source:
    """A file with its comments blanked and every string's body blanked, quotes kept.

    `masked` has the text's length and line breaks, so an index or a line in
    it is the same in the text. `strings` maps the index of each string or
    template literal's opening quote to its value (None for a template with a
    substitution) and the index after it. `close` and `open` pair the brackets
    of the masked text, and `parent` gives each opening bracket the one that
    encloses it (-1 at the top level).
    """

    text: str
    masked: str
    strings: dict[int, tuple[str | None, int]]
    close: dict[int, int]
    open: dict[int, int]
    parent: dict[int, int]


def scan(text: str) -> Source:
    """Blank comments and string bodies (template substitutions are code), then pair brackets."""
    n = len(text)
    out = list(text)
    strings: dict[int, tuple[str | None, int]] = {}

    def blank(a: int, b: int) -> None:
        for k in range(a, b):
            if out[k] != "\n":
                out[k] = " "

    def regex_end(i: int) -> int | None:
        j, in_class = i + 1, False
        while j < n:
            c = text[j]
            if c == "\n":
                return None
            if c == "\\":
                j += 2
                continue
            if c == "[":
                in_class = True
            elif c == "]":
                in_class = False
            elif c == "/" and not in_class:
                j += 1
                while j < n and (text[j].isalnum() or text[j] == "_"):
                    j += 1
                return j
            j += 1
        return None

    def template(i: int) -> int:
        j, substituted = i + 1, False
        while j < n:
            c = text[j]
            if c == "\\":
                blank(j, j + 2)
                j += 2
                continue
            if c == "`":
                lit = None if substituted else string_at(text, i)
                strings[i] = (lit[0] if lit else None, j + 1)
                return j + 1
            if c == "$" and text[j + 1 : j + 2] == "{":
                substituted = True
                blank(j, j + 2)
                end = code(j + 2, nested=True)
                blank(end - 1, end)
                j = end
                continue
            blank(j, j + 1)
            j += 1
        raise Unparsed("an unterminated template literal")

    def code(i: int, nested: bool) -> int:
        depth, prev = 0, ""
        while i < n:
            c = text[i]
            if c.isspace():
                i += 1
            elif text.startswith("//", i):
                j = text.find("\n", i)
                j = n if j < 0 else j
                blank(i, j)
                i = j
            elif text.startswith("/*", i):
                j = text.find("*/", i + 2)
                if j < 0:
                    raise Unparsed("an unterminated comment")
                blank(i, j + 2)
                i = j + 2
            elif c in "'\"":
                lit = string_at(text, i)
                if lit is None:
                    raise Unparsed(f"an unterminated string at offset {i}")
                strings[i] = (lit[0], lit[1])
                blank(i + 1, lit[1] - 1)
                i, prev = lit[1], "value"
            elif c == "`":
                i, prev = template(i), "value"
            elif c == "/" and (prev == "" or prev in _REGEX_AFTER or prev in _REGEX_WORDS):
                end = regex_end(i)
                if end is None:
                    i, prev = i + 1, c
                else:
                    blank(i + 1, end)
                    i, prev = end, "value"
            elif c == "{":
                depth, i, prev = depth + 1, i + 1, c
            elif c == "}":
                if nested and depth == 0:
                    return i + 1
                depth, i, prev = depth - 1, i + 1, c
            elif (m := _IDENT.match(text, i)) is not None:
                word = m.group(0)
                i, prev = m.end(), word if word in _REGEX_WORDS else "value"
            elif c.isdigit():
                while i < n and (text[i].isalnum() or text[i] in "._"):
                    i += 1
                prev = "value"
            else:
                i, prev = i + 1, ("value" if c in ")]" else c)
        if nested:
            raise Unparsed("an unterminated template substitution")
        return n

    code(0, nested=False)
    masked = "".join(out)
    close: dict[int, int] = {}
    parent: dict[int, int] = {}
    stack: list[int] = []
    pairs = {")": "(", "]": "[", "}": "{"}
    for k, c in enumerate(masked):
        if c in "([{":
            parent[k] = stack[-1] if stack else -1
            stack.append(k)
        elif c in pairs:
            if not stack or masked[stack[-1]] != pairs[c]:
                raise Unparsed(f"an unmatched {c!r} at offset {k}")
            close[stack.pop()] = k
    if stack:
        raise Unparsed(f"an unclosed {masked[stack[-1]]!r} at offset {stack[-1]}")
    return Source(text, masked, strings, close, {v: k for k, v in close.items()}, parent)


def _ws(src: Source, i: int) -> int:
    while i < len(src.masked) and src.masked[i].isspace():
        i += 1
    return i


def _back(src: Source, i: int) -> int:
    while i >= 0 and src.masked[i].isspace():
        i -= 1
    return i


def title_at(src: Source, i: int, consts: Mapping[str, str]) -> str | None:
    """The constant string expression at i: literals and known constants joined by `+`."""
    parts: list[str] = []
    while True:
        i = _ws(src, i)
        if i in src.strings:
            value, i = src.strings[i]
            if value is None:
                return None
            parts.append(value)
        elif (m := _IDENT.match(src.masked, i)) is not None and m.group(0) in consts:
            parts.append(consts[m.group(0)])
            i = m.end()
        else:
            return None
        j = _ws(src, i)
        if j < len(src.masked) and src.masked[j] == "+":
            i = j + 1
            continue
        if re.compile(r"\s*(?:as\s+const\b\s*)?[,;)\n]").match(src.masked, i):
            return "".join(parts)
        return None


def constants(src: Source) -> dict[str, str]:
    """Every `const NAME = <constant string expression>` in the file, in order of appearance."""
    found: dict[str, str] = {}
    for m in _CONST.finditer(src.masked):
        value = title_at(src, m.end(), found)
        if value is not None:
            found[m.group(1)] = value
    return found


def _chain(src: Source, q: int) -> list[str | int] | None:
    """The callee before the `(` at q, outermost first: names, and the `(` index of each call."""
    items: list[str | int] = []
    j = _back(src, q - 1)
    while j >= 0:
        if src.masked[j] == ")":
            o = src.open[j]
            items.insert(0, o)
            j = _back(src, o - 1)
            continue
        k = j
        while k >= 0 and (src.masked[k].isalnum() or src.masked[k] in "_$"):
            k -= 1
        if k == j:
            return None
        items.insert(0, src.masked[k + 1 : j + 1])
        j = _back(src, k)
        if j >= 0 and src.masked[j] == ".":
            j = _back(src, j - 1)
            continue
        if j >= 0 and (src.masked[j].isalnum() or src.masked[j] in "_$"):
            return None
        break
    return items or None


class _Opaque:
    """A table value that is not a literal: a title that shows it cannot be known."""

    def __repr__(self) -> str:
        return "OPAQUE"


OPAQUE = _Opaque()


def _skip_expr(src: Source, j: int, end: int) -> int:
    """The index of the `,` (or `end`) that ends the expression at j inside a list or object."""
    while j < end:
        c = src.masked[j]
        if c in "([{":
            j = src.close[j] + 1
        elif c == ",":
            return j
        else:
            j += 1
    return end


def _element(src: Source, j: int, end: int) -> tuple[Any, int]:
    """A list element or property value: a literal (an `as` cast kept), else OPAQUE."""
    try:
        value, k = _literal(src, j)
    except Unparsed:
        return OPAQUE, _skip_expr(src, j, end)
    k = _ws(src, k)
    if k < end and src.masked[k] not in ",":
        cast = re.compile(r"as(?![\w$])").match(src.masked, k)
        return (value if cast else OPAQUE), _skip_expr(src, k, end)
    return value, k


def _literal(src: Source, i: int) -> tuple[Any, int]:
    """The JSON-like literal at i (string, number, boolean, null, array or object) and its end.

    Inside a list or an object, an element that is not a literal is OPAQUE.
    """
    i = _ws(src, i)
    m = src.masked
    if i in src.strings:
        text, end = src.strings[i]
        if text is None:
            raise Unparsed("a template with a substitution")
        return text, end
    if m[i] in "[{":
        end = src.close[i]
        values: list[Any] = []
        keyed: dict[str, Any] = {}
        j = _ws(src, i + 1)
        while j < end:
            if m[i] == "{":
                quoted = src.strings.get(j, (None, j))
                if quoted[0] is not None:
                    key, j = quoted[0], quoted[1]
                elif (km := _IDENT.match(m, j)) is not None:
                    key, j = km.group(0), km.end()
                else:
                    raise Unparsed("an object key")
                j = _ws(src, j)
                if m[j] != ":":
                    raise Unparsed("a shorthand property")
                keyed[key], j = _element(src, _ws(src, j + 1), end)
            else:
                element, j = _element(src, j, end)
                values.append(element)
            j = _ws(src, j)
            if j < end and m[j] == ",":
                j = _ws(src, j + 1)
            elif j != end:
                raise Unparsed("a list")
        return (keyed if m[i] == "{" else values), end + 1
    if (num := _NUMBER.match(m, i)) is not None:
        number = float(num.group(0))
        return (int(number) if number.is_integer() else number), num.end()
    for word, constant in (("true", True), ("false", False), ("null", None)):
        if re.compile(rf"{word}(?![\w$])").match(m, i):
            return constant, i + len(word)
    raise Unparsed("a value that is not a literal")


_AFTER_TABLE = re.compile(r"\s*(?:as\s+const\s*)?,?\s*")


def table_constants(src: Source) -> dict[str, int]:
    """Every `const NAME = [ ... ]` of the file: the index of its `[`, for `.each(NAME)`."""
    found: dict[str, int] = {}
    for m in _CONST.finditer(src.masked):
        i = _ws(src, m.end())
        if i < len(src.masked) and src.masked[i] == "[":
            found[m.group(1)] = i
    return found


def _rows(src: Source, i: int) -> tuple[list[Any], int] | None:
    try:
        rows, end = _literal(src, i)
    except Unparsed:
        return None
    return (rows, end) if isinstance(rows, list) and rows else None


def _table(src: Source, o: int, tables: Mapping[str, int]) -> list[Any] | None:
    """The rows of a `.each(...)` or `.for(...)` table whose `(` is at o, or None.

    The table is an array literal, or the name of a `const` bound to one in
    the same file; either may end in `as const`.
    """
    i = _ws(src, o + 1)
    if src.masked[i] == "[":
        found = _rows(src, i)
        if found is None or not _AFTER_TABLE.fullmatch(src.masked, found[1], src.close[o]):
            return None
        return found[0]
    m = _IDENT.match(src.masked, i)
    if (
        m is None
        or m.group(0) not in tables
        or not _AFTER_TABLE.fullmatch(src.masked, m.end(), src.close[o])
    ):
        return None
    found = _rows(src, tables[m.group(0)])
    if found is None or not re.compile(r"\s*(?:as\s+const\b)?\s*[;\n]").match(src.masked, found[1]):
        return None
    return found[0]


def _display(value: Any, spec: str) -> str | None:
    if spec == "%j":
        try:
            return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        except TypeError:  # an OPAQUE value inside
            return None
    if isinstance(value, bool):
        return {"%s": str(value).lower(), "%d": str(int(value))}.get(spec)
    if isinstance(value, int):
        return str(value)
    if value is None:
        return "null" if spec == "%s" else None
    if isinstance(value, str) and spec == "%s":
        return value
    return None


def _attribute(text: str, items: list[Any]) -> str | None:
    """vitest's `$key` interpolation: a key of an object row, or an index of an array row."""
    objects = isinstance(items[0], dict)
    if items[0] is OPAQUE and re.search(r"\$[$\w.]", text):
        return None  # an object row vitest would interpolate, or not: unknown
    out, pos = [], 0
    for m in re.finditer(r"\$([$\w.]+)", text):
        key = m.group(1)
        out.append(text[pos : m.start()])
        pos = m.end()
        if not objects and not key.isdigit():
            out.append(m.group(0))
            continue
        if "." in key or "$" in key:
            return None
        if objects:
            if key not in items[0]:
                return None
            value = items[0][key]
        else:
            if int(key) >= len(items):
                return None
            value = items[int(key)]
        if isinstance(value, str):
            out.append(value if len(value) <= TRUNCATE else value[: TRUNCATE - 1] + "…")
        elif (shown := _display(value, "%s")) is not None and not isinstance(value, float):
            out.append(shown)
        else:
            return None
    out.append(text[pos:])
    return "".join(out)


def format_title(template: str, row: Any, index: int) -> str | None:
    """A `.each` or `.for` row's title as vitest formats it, for %s, %d, %i, %#, %$ and $key."""
    items = row if isinstance(row, list) else [row]
    if not items or "%%" in template:
        return None
    template = template.replace("%#", str(index)).replace("%$", str(index + 1))
    out, pos, k = [], 0, 0
    for m in re.finditer(r"%[sdjifoOc%]", template):
        before = _attribute(template[pos : m.start()], items)
        if before is None or m.group(0) not in ("%s", "%d", "%i", "%j") or k >= len(items):
            return None
        shown = _display(items[k], m.group(0))
        if shown is None:
            return None
        out += [before, shown]
        pos, k = m.end(), k + 1
    after = _attribute(template[pos:], items)
    if after is None:
        return None
    return "".join([*out, after])


@dataclass(frozen=True)
class Call:
    kind: str  # "describe" or "test"
    titles: tuple[str, ...]  # what vitest names it; empty when not a constant
    paren: int  # index of the call's own `(`
    line: int  # zero-based
    modifiers: frozenset[str]
    blocked: bool  # skipped, todo, failing or conditional: no evidence


def calls(source: str | Source) -> list[Call]:
    """The describe, it and test calls of a file, with their titles and what blocks them."""
    src = scan(source) if isinstance(source, str) else source
    consts = constants(src)
    tables = table_constants(src)
    found: list[Call] = []
    for q in sorted(src.close):
        if src.masked[q] != "(":
            continue
        chain = _chain(src, q)
        if not chain or chain[0] not in _BASES:
            continue
        names = [c for c in chain[1:] if isinstance(c, str)]
        if not set(names) <= _MODIFIERS:
            continue
        last = chain[-1]
        if isinstance(last, str) and last in _TABLES | _CONDITIONS:
            continue  # the table or the condition, not the block
        table: int | None = None
        for a, b in itertools.pairwise(chain):
            if isinstance(b, int):
                if not isinstance(a, str) or a not in _TABLES | _CONDITIONS:
                    break
                if a in _TABLES:
                    table = b
        else:
            found.append(_call(src, q, str(chain[0]), frozenset(names), table, consts, tables))
    return found


def _call(
    src: Source,
    q: int,
    base: str,
    names: frozenset[str],
    table: int | None,
    consts: Mapping[str, str],
    tables: Mapping[str, int],
) -> Call:
    title = title_at(src, q + 1, consts)
    titles: tuple[str, ...] = ()
    if title is not None and table is None:
        titles = (title,)
    elif title is not None and table is not None:
        rows = _table(src, table, tables)
        formatted = [format_title(title, r, i) for i, r in enumerate(rows or [])]
        titles = tuple(t for t in formatted if t is not None)
    kind = "describe" if base == "describe" else "test"
    body = src.masked[q : src.close[q] + 1]
    options = any(
        _OPTIONS_SKIP.search(src.masked, b, src.close[b])
        for b, p in src.parent.items()
        if p == q and src.masked[b] == "{" and src.masked[_back(src, b - 1)] == ","
    )
    blocked = bool(names & ({"skip", "todo", "fails"} | _CONDITIONS)) or options
    if kind == "test" and _CONTEXT_SKIP.search(body):
        blocked = True
    line = src.masked.count("\n", 0, q)
    return Call(kind, titles, q, line, names, blocked)


def _function_body(src: Source, b: int, owner: int) -> bool:
    """Whether the `{` at b is the body of a function passed straight to the call at owner."""
    before = _back(src, b - 1)
    return (
        src.masked[b] == "{"
        and src.parent.get(b) == owner
        and before >= 0
        and (src.masked[before] == ")" or src.masked[before - 1 : before + 1] == "=>")
    )


def ancestry(src: Source, call: Call, describes: Mapping[int, Call]) -> tuple[list[Call], bool]:
    """The describe calls enclosing a call, outermost first, and whether any other block does.

    A test is plainly in a describe when every bracket around it is a
    describe call or the body of the function passed to one. Anything else
    (an `if`, a loop, a helper function, a callback such as `forEach`) makes
    it enclosed: whether it runs is not decided by its describes.
    """
    chain: list[Call] = []
    enclosed, awaiting = False, None
    path: list[int] = []
    p = src.parent[call.paren]
    while p != -1:
        path.insert(0, p)
        p = src.parent[p]
    for b in path:
        if awaiting is not None and _function_body(src, b, awaiting):
            awaiting = None
        elif awaiting is None and b in describes:
            chain.append(describes[b])
            awaiting = b
        else:
            enclosed, awaiting = True, (b if b in describes else None)
            if b in describes:
                chain.append(describes[b])
    return chain, enclosed or awaiting is not None


def test_status(text: str, describe: Sequence[str], it: str, enclosed: bool = False) -> str:
    """Whether a named test is in the file: found, missing, skipped, enclosed or unparsed.

    The named describes must enclose the test in order, not necessarily
    directly. A skip, todo, fails, skipIf or runIf on the test or on any
    enclosing describe, a `skip: true` options object, or a call to a context's
    `skip` in its body makes it skipped. A test inside any block that is not a
    describe is enclosed, and counts only when the config says so.
    """
    try:
        src = scan(text)
    except Unparsed:
        return "unparsed"
    found = calls(src)
    describes = {c.paren: c for c in found if c.kind == "describe"}
    status = "missing"
    for c in found:
        if c.kind != "test" or it not in c.titles:
            continue
        chain, boxed = ancestry(src, c, describes)
        k = 0
        for d in chain:
            if k < len(describe) and describe[k] in d.titles:
                k += 1
        if k < len(describe):
            continue
        if c.blocked or any(d.blocked for d in chain):
            status = "skipped"
        elif boxed and not enclosed:
            status = "enclosed" if status == "missing" else status
        else:
            return "found"
    return status


def find_test(text: str, describe: Sequence[str], it: str, enclosed: bool = False) -> bool:
    """Whether the file holds the named test as evidence (see `test_status`)."""
    return test_status(text, describe, it, enclosed) == "found"


# The crosswalk.


class ConfigError(ValueError):
    pass


def _texts(value: Any) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [t for v in value for t in _texts(v)]
    if isinstance(value, dict):
        return [t for v in value.values() for t in _texts(v)]
    return []


def validate(config: Mapping[str, Any]) -> None:
    """Refuse a config the crosswalk cannot stand behind; the reasons name the row."""
    obligations = config.get("obligations")
    claims = config.get("claims")
    sources = config.get("sources")
    if not isinstance(obligations, list) or not isinstance(claims, list) or not claims:
        raise ConfigError("the config needs a list of obligations and a non-empty list of claims")
    if not isinstance(sources, dict):
        raise ConfigError("the config needs a sources object naming each instrument's primary text")
    oids: set[str] = set()
    for ob in obligations:
        oid = ob.get("id")
        if not isinstance(oid, str) or oid in oids:
            raise ConfigError(f"obligation {oid!r}: a missing or repeated id")
        oids.add(oid)
        if ob.get("instrument") not in sources:
            raise ConfigError(
                f"obligation {oid}: instrument {ob.get('instrument')!r} has no source"
            )
        if not isinstance(ob.get("article"), str) or not ob["article"]:
            raise ConfigError(f"obligation {oid}: an article is required")
        if not isinstance(ob.get("paragraph"), str) or not ob["paragraph"]:
            raise ConfigError(f"obligation {oid}: a paragraph is required")
        if not isinstance(ob.get("quote"), str) or not ob["quote"].strip():
            raise ConfigError(f"obligation {oid}: a quote from the primary text is required")
    cids: set[str] = set()
    for claim in claims:
        cid = claim.get("id")
        if not isinstance(cid, str) or cid in cids:
            raise ConfigError(f"claim {cid!r}: a missing or repeated id")
        cids.add(cid)
        for key in ("claim", "source"):
            if not isinstance(claim.get(key), str) or not claim[key].strip():
                raise ConfigError(f"claim {cid}: {key} is required")
        tests = claim.get("tests")
        if not isinstance(tests, list):
            raise ConfigError(f"claim {cid}: tests is a list, empty when no test proves it")
        for t in tests:
            if not isinstance(t.get("file"), str) or not isinstance(t.get("it"), str):
                raise ConfigError(f"claim {cid}: each test names a file and an it title")
            if not isinstance(t.get("describe"), list) or not all(
                isinstance(d, str) for d in t["describe"]
            ):
                raise ConfigError(f"claim {cid}: a test's describe is a list of titles")
            if "enclosed" in t and not (isinstance(t["enclosed"], str) and t["enclosed"].strip()):
                raise ConfigError(
                    f"claim {cid}: enclosed says which block encloses the test and why it runs"
                )
        if not tests and not str(claim.get("gap", "")).strip():
            raise ConfigError(f"claim {cid}: a claim with no test says why in gap")
        if tests and claim.get("gap"):
            raise ConfigError(f"claim {cid}: gap is only for a claim with no test")
        links = claim.get("obligations")
        unmapped = str(claim.get("unmapped", "")).strip()
        if not isinstance(links, list) or (not links and not unmapped):
            raise ConfigError(
                f"claim {cid}: name at least one obligation it bears on, "
                f"or say in unmapped why none is cited"
            )
        if links and unmapped:
            raise ConfigError(f"claim {cid}: unmapped is only for a claim citing no obligation")
        for link in links:
            if link.get("id") not in oids:
                raise ConfigError(f"claim {cid}: unknown obligation {link.get('id')!r}")
            if link.get("relation") != RELATION:
                raise ConfigError(
                    f"claim {cid}: the relation to {link['id']} is {RELATION!r}, never another"
                )
            if not isinstance(link.get("why"), str) or not link["why"].strip():
                raise ConfigError(f"claim {cid}: say why it bears on {link['id']}")
    for row in [*claims, *obligations]:
        # A quotation is the act's text and a test title is the code's: neither is ours.
        for text in _texts({k: v for k, v in row.items() if k not in ("quote", "tests")}):
            if words := forbidden_words(text, ()):
                raise ConfigError(
                    f"row {row.get('id')}: {words[0]!r} reads as a compliance claim; "
                    f"a row bears on an obligation, never meets it"
                )
    for key in ("statement", "method"):
        if words := forbidden_words(str(config.get(key, "")), NEGATIONS):
            raise ConfigError(f"{key}: {words[0]!r} reads as a compliance claim")


def forbidden_words(text: str, allowed: Sequence[str]) -> list[str]:
    """The compliance words in a text, once each allowed phrase is set aside (any case)."""
    folded = re.sub(r"\s+", " ", text).lower()
    for phrase in allowed:
        folded = folded.replace(phrase, " ")
    return [m.group(0) for m in FORBIDDEN_WORDS.finditer(folded)]


def test_ref(t: Mapping[str, Any]) -> str:
    return " > ".join([t["file"], *t["describe"], t["it"]])


def build(root: Path, config: Mapping[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """The crosswalk result and the named tests that do not exist under `root`."""
    validate(config)
    missing: list[str] = []
    texts: dict[str, str | None] = {}
    obligations = {ob["id"]: ob for ob in config["obligations"]}
    rows: list[dict[str, Any]] = []
    for claim in config["claims"]:
        tests = []
        for t in claim["tests"]:
            if t["file"] not in texts:
                path = root / t["file"]
                texts[t["file"]] = path.read_text(encoding="utf-8") if path.is_file() else None
            text = texts[t["file"]]
            if text is None:
                missing.append(f"{claim['id']}: no file {t['file']}")
            else:
                status = test_status(text, t["describe"], t["it"], bool(t.get("enclosed")))
                if status != "found":
                    missing.append(f"{claim['id']}: no test {test_ref(t)} ({status})")
            tests.append(
                {
                    "file": t["file"],
                    "describe": t["describe"],
                    "it": t["it"],
                    **({"enclosed": t["enclosed"]} if t.get("enclosed") else {}),
                }
            )
        rows.append(
            {
                "id": claim["id"],
                "claim": claim["claim"],
                "source": claim["source"],
                "invariant": claim.get("invariant"),
                "status": "evidenced" if tests else "not evidenced",
                "tests": tests,
                "gap": claim.get("gap"),
                "limits": claim.get("limits"),
                "unmapped": claim.get("unmapped"),
                "obligations": [
                    {"id": link["id"], "relation": link["relation"], "why": link["why"]}
                    for link in claim["obligations"]
                ],
            }
        )
    by_obligation: dict[str, list[str]] = {oid: [] for oid in obligations}
    for row in rows:
        for link in row["obligations"]:
            by_obligation[link["id"]].append(row["id"])
    result = {
        "name": config.get("name", "crosswalk"),
        "card": "R4",
        "hypothesis": "none",
        "statement": config["statement"],
        "relation": RELATION,
        "sources": config["sources"],
        "obligations": [
            {
                **{k: ob.get(k) for k in ("id", "instrument", "article", "paragraph", "point")},
                "heading": ob.get("heading"),
                "quote": ob["quote"],
                "claims": by_obligation[ob["id"]],
            }
            for ob in config["obligations"]
        ],
        "claims": rows,
        "summary": {
            "claims": len(rows),
            "evidenced": sum(r["status"] == "evidenced" for r in rows),
            "not_evidenced": [r["id"] for r in rows if r["status"] == "not evidenced"],
            "tests": sum(len(r["tests"]) for r in rows),
            "test_files": len({t["file"] for r in rows for t in r["tests"]}),
            "obligations": len(obligations),
            "obligations_without_claim": [o for o, c in by_obligation.items() if not c],
            "claims_unmapped": [r["id"] for r in rows if not r["obligations"]],
        },
    }
    return result, missing


# The thesis table.


def cite(ob: Mapping[str, Any], sources: Mapping[str, Any]) -> str:
    short = sources[ob["instrument"]]["short"]
    point = "".join(f"({p})" for p in ob["point"].split(".")) if ob.get("point") else ""
    return f"{short} Art. {ob['article']}({ob['paragraph']}){point}"


def render_table(result: Mapping[str, Any]) -> str:
    obligations = {ob["id"]: ob for ob in result["obligations"]}
    lines = [
        "| id | claim | evidence | obligations it bears on | limits |",
        "|---|---|---|---|---|",
    ]
    for row in result["claims"]:
        if row["tests"]:
            evidence = "<br>".join(
                f"`{t['file']}`: {' > '.join(t['describe'] + [t['it']])}" for t in row["tests"]
            )
        else:
            evidence = f"**not evidenced**: {row['gap']}"
        cites = "; ".join(cite(obligations[o["id"]], result["sources"]) for o in row["obligations"])
        if not cites:
            cites = f"none cited: {row['unmapped']}"
        claim = row["claim"] + (f" (invariant {row['invariant']})" if row["invariant"] else "")
        limits = _cell(row["limits"] or "")
        lines.append(
            f"| {row['id']} | {_cell(claim)} | {_cell(evidence)} | {_cell(cites)} | {limits} |"
        )
    return "\n".join(lines) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def write_table(path: Path, table: str) -> None:
    text = path.read_text(encoding="utf-8")
    start = text.find(TABLE_BEGIN)
    end = text.find(TABLE_END)
    if start < 0 or end < start:
        raise ConfigError(f"{path.name}: no crosswalk table markers")
    head = text[: start + len(TABLE_BEGIN)]
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(head + "\n\n" + table + "\n" + text[end:])


def prose(text: str) -> str:
    """A Markdown file's text outside the generated table (whose rows `validate` checks)."""
    start, end = text.find(TABLE_BEGIN), text.find(TABLE_END)
    if start < 0 or end < start:
        return text
    return text[:start] + text[end + len(TABLE_END) :]


def table_in(path: Path) -> str:
    """The table between the markers of a Markdown file, as `write_table` put it there."""
    text = path.read_text(encoding="utf-8")
    start = text.find(TABLE_BEGIN)
    end = text.find(TABLE_END)
    if start < 0 or end < start:
        raise ConfigError(f"{path.name}: no crosswalk table markers")
    return text[start + len(TABLE_BEGIN) : end].strip("\n") + "\n"


# The primary legal texts.


def legal_lines(xhtml: str) -> list[str]:
    """The Official Journal XHTML as plain lines, one per paragraph or cell, whitespace folded."""
    text = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", xhtml, flags=re.S)
    text = re.sub(r"</(p|div|tr|td|h\d|li)>", "\n", text)
    text = html.unescape(re.sub(r"<[^>]+>", " ", text))
    lines = (re.sub(r"\s+", " ", ln).strip() for ln in text.splitlines())
    return [ln for ln in lines if ln]


def _fold(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u2019", "'")).strip()


def _article(lines: Sequence[str], article: str) -> int:
    head = f"Article {article}"
    try:
        return lines.index(head)
    except ValueError as e:
        raise ConfigError(f"no {head}") from e


def article_heading(lines: Sequence[str], article: str) -> str:
    """The heading line of an article: the line after its `Article N` line."""
    start = _article(lines, article)
    return lines[start + 1] if start + 1 < len(lines) else ""


def locate(lines: Sequence[str], article: str, paragraph: str, point: str | None) -> str:
    """The text of one article's paragraph (and point), from the plain lines of the act."""
    head = f"Article {article}"
    start = _article(lines, article)
    end = next(
        (k for k in range(start + 1, len(lines)) if re.fullmatch(r"Article \d+[a-z]?", lines[k])),
        len(lines),
    )
    body = list(lines[start + 1 : end])
    marks = [k for k, ln in enumerate(body) if re.match(rf"{re.escape(paragraph)}\. ", ln)]
    if not marks:
        raise ConfigError(f"{head} has no paragraph {paragraph}")
    p0 = marks[0]
    p1 = next(
        (k for k in range(p0 + 1, len(body)) if re.match(r"\d+\. ", body[k])),
        len(body),
    )
    para = body[p0:p1]
    if point is None:
        return " ".join(para)
    letter, _, roman = point.partition(".")
    try:
        q0 = para.index(f"({letter})")
    except ValueError as e:
        raise ConfigError(f"{head}({paragraph}) has no point ({letter})") from e
    after = f"({chr(ord(letter) + 1)})"
    q1 = next((k for k in range(q0 + 1, len(para)) if para[k] == after), len(para))
    seg = para[q0:q1]
    if not roman:
        return " ".join(seg)
    try:
        r0 = seg.index(f"({roman})")
    except ValueError as e:
        raise ConfigError(f"{head}({paragraph})({letter}) has no point ({roman})") from e
    r1 = next(
        (k for k in range(r0 + 1, len(seg)) if re.fullmatch(r"\([ivx]+\)", seg[k])),
        len(seg),
    )
    return " ".join(seg[r0:r1])


def check_legal(config: Mapping[str, Any], folder: Path) -> list[str]:
    """Problems with the quotes: each must stand in the article, paragraph and point it cites."""
    problems: list[str] = []
    lines: dict[str, list[str]] = {}
    for key, src in config["sources"].items():
        path = folder / src["file"]
        if not path.is_file():
            problems.append(f"{key}: no {src['file']} in the legal folder")
            continue
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != src["sha256"]:
            problems.append(f"{key}: {src['file']} does not hash to the config's sha256")
            continue
        lines[key] = legal_lines(data.decode("utf-8"))
    for ob in config["obligations"]:
        if ob["instrument"] not in lines:
            continue
        try:
            text = locate(lines[ob["instrument"]], ob["article"], ob["paragraph"], ob.get("point"))
        except ConfigError as e:
            problems.append(f"{ob['id']}: {e}")
            continue
        if _fold(ob["quote"]) not in _fold(text):
            problems.append(f"{ob['id']}: the quote is not in {cite(ob, config['sources'])}")
        heading = article_heading(lines[ob["instrument"]], ob["article"])
        if ob.get("heading") and ob["heading"] != heading:
            problems.append(
                f"{ob['id']}: Article {ob['article']}'s heading is {heading!r}, "
                f"not {ob['heading']!r}"
            )
    return problems


def fetch_legal(config: Mapping[str, Any], folder: Path) -> None:
    """Fetch each primary text the config names from the Publications Office (data only)."""
    if os.environ.get("ENGRAM_OFFLINE") == "1":
        raise SystemExit("crosswalk: refusing to fetch the legal texts under ENGRAM_OFFLINE=1")
    folder.mkdir(parents=True, exist_ok=True)
    for src in config["sources"].values():
        request = urllib.request.Request(
            src["url"],
            headers={"Accept": "application/xhtml+xml", "Accept-Language": "eng"},
        )
        with urllib.request.urlopen(request, timeout=120) as response:
            (folder / src["file"]).write_bytes(response.read())


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--root", type=Path, default=REPO)
    parser.add_argument(
        "--table", type=Path, help="a Markdown file whose crosswalk block to rewrite"
    )
    parser.add_argument("--legal", type=Path, help="a folder holding the primary legal texts")
    parser.add_argument("--fetch", action="store_true", help="fetch the legal texts into --legal")
    args = parser.parse_args(argv)
    config = load_config(args.config)
    try:
        result, missing = build(args.root.resolve(), config)
    except ConfigError as e:
        print(f"crosswalk: {e}", file=sys.stderr)
        return 2
    if missing:
        for m in missing:
            print(f"crosswalk: missing {m}", file=sys.stderr)
        print(
            f"crosswalk: {len(missing)} named tests do not exist; nothing written", file=sys.stderr
        )
        return 1
    if args.legal is not None:
        if args.fetch:
            fetch_legal(config, args.legal)
        problems = check_legal(config, args.legal)
        for p in problems:
            print(f"crosswalk: legal {p}", file=sys.stderr)
        if problems:
            return 1
        print(f"crosswalk: {len(config['obligations'])} quotes stand in the primary texts")
    write_result(args.out, result)
    if args.table is not None:
        if words := forbidden_words(prose(args.table.read_text(encoding="utf-8")), NEGATIONS):
            print(f"crosswalk: {args.table.name}: {words[0]!r} reads as a compliance claim")
            return 2
        write_table(args.table, render_table(result))
    s = result["summary"]
    print(
        f"crosswalk: {s['claims']} claims, {s['evidenced']} evidenced by {s['tests']} tests "
        f"in {s['test_files']} files, {len(s['not_evidenced'])} not evidenced, "
        f"{s['obligations']} obligations"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
