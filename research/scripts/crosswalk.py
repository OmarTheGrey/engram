RELATION = "bears on"
STATUSES = ("evidenced", "not evidenced")
NO_EVIDENCE = frozenset({"skip", "todo", "fails"})
TABLE_BEGIN = "<!-- crosswalk:table:begin (generated by research/scripts/crosswalk.py) -->"
TABLE_END = "<!-- crosswalk:table:end -->"
FORBIDDEN_WORDS = ("satisf", "complies", "compliant", "fulfil", "meets the")

_CALL = re.compile(
    r"(?<![\w.$])(describe|it|test)((?:\s*\.\s*(?:only|skip|todo|fails|concurrent|sequential))*)\s*\("
)
_EACH = re.compile(r"(?<![\w.$])(describe|it|test)\s*\.\s*each\s*\(\s*\[")
_CONST = re.compile(r"(?<![\w.$])const\s+([A-Za-z_$][\w$]*)\s*=\s*")
_IDENT = re.compile(r"[A-Za-z_$][\w$]*")
_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "0": "\0", "b": "\b", "f": "\f", "v": "\v"}


# Titles in a TypeScript test file.


def string_at(text: str, i: int) -> tuple[str, int] | None:
    """The JavaScript string literal starting at text[i] and the index after it, or None.

    A template literal with a `${` substitution is not a constant and gives None.
    """
    if i >= len(text) or text[i] not in "\"'`":
        return None
    quote = text[i]
    out: list[str] = []
    j = i + 1
    while j < len(text):
        c = text[j]
        if c == "\\":
            if j + 1 >= len(text):
                return None
            nxt = text[j + 1]
            if nxt == "\n":
                j += 2
                continue
            if nxt == "u" and text[j + 2 : j + 3] == "{":
                end = text.find("}", j + 3)
                if end < 0:
                    return None
                out.append(chr(int(text[j + 3 : end], 16)))
                j = end + 1
                continue
            if nxt == "u":
                out.append(chr(int(text[j + 2 : j + 6], 16)))
                j += 6
                continue
            if nxt == "x":
                out.append(chr(int(text[j + 2 : j + 4], 16)))
                j += 4
                continue
            out.append(_ESCAPES.get(nxt, nxt))
            j += 2
            continue
        if quote == "`" and c == "$" and text[j + 1 : j + 2] == "{":
            return None
        if c == quote:
            return "".join(out), j + 1
        if c == "\n" and quote != "`":
            return None
        out.append(c)
        j += 1
    return None


def _skip_space(text: str, i: int) -> int:
    while i < len(text) and text[i].isspace():
        i += 1
    return i


def title_at(text: str, i: int, consts: Mapping[str, str]) -> str | None:
    """The constant string expression at text[i]: literals and known constants joined by `+`."""
    parts: list[str] = []
    while True:
        i = _skip_space(text, i)
        lit = string_at(text, i)
        if lit is not None:
            parts.append(lit[0])
            i = lit[1]
        else:
            m = _IDENT.match(text, i)
            if m is None or m.group(0) not in consts:
                return None
            parts.append(consts[m.group(0)])
            i = m.end()
        j = _skip_space(text, i)
        if j < len(text) and text[j] == "+":
            i = j + 1
            continue
        if j < len(text) and text[j] in ",;)\n":
            return "".join(parts)
        return None


def constants(text: str) -> dict[str, str]:
    """Every `const NAME = <constant string expression>` in the file, in order of appearance."""
    found: dict[str, str] = {}
    for m in _CONST.finditer(text):
        value = title_at(text, m.end(), found)
        if value is not None:
            found[m.group(1)] = value
    return found


@dataclass(frozen=True)
class Call:
    kind: str  # "describe" or "test"
    title: str
    line: int  # zero-based line of the call
    indent: int
    modifiers: frozenset[str]


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" \t"))


def each_titles(text: str, i: int, consts: Mapping[str, str]) -> list[str] | None:
    """The titles of `.each([...])("... %s ...")` from the `[` at text[i]: one per row.

    A row is a string literal or an array of them; each `%s` of the title takes
    the row's next value, as vitest formats it. Any other table, or a title
    with another placeholder, gives None.
    """
    rows: list[list[str]] = []
    i = _skip_space(text, i + 1)
    while i < len(text) and text[i] != "]":
        row = _each_row(text, i)
        if row is None:
            return None
        rows.append(row[0])
        i = _skip_space(text, row[1])
        if i < len(text) and text[i] == ",":
            i = _skip_space(text, i + 1)
    m = re.compile(r"\]\s*\)\s*\(").match(text, i)
    if m is None or not rows:
        return None
    title = title_at(text, m.end(), consts)
    if title is None or re.search(r"%[^s]|\$", title):
        return None
    slots = title.count("%s")
    if slots == 0 or any(len(r) < slots for r in rows):
        return None
    titles = []
    for values in rows:
        out = title
        for value in values[:slots]:
            out = out.replace("%s", value, 1)
        titles.append(out)
    return titles


def _each_row(text: str, i: int) -> tuple[list[str], int] | None:
    lit = string_at(text, i)
    if lit is not None:
        return [lit[0]], lit[1]
    if text[i] != "[":
        return None
    values: list[str] = []
    i = _skip_space(text, i + 1)
    while i < len(text) and text[i] != "]":
        lit = string_at(text, i)
        if lit is None:
            return None
        values.append(lit[0])
        i = _skip_space(text, lit[1])
        if i < len(text) and text[i] == ",":
            i = _skip_space(text, i + 1)
    return (values, i + 1) if values else None


def calls(text: str) -> list[Call]:
    """The describe, it and test calls of a file whose title is a constant string."""
    consts = constants(text)
    line_starts = [0] + [m.end() for m in re.finditer("\n", text)]
    lines = text.split("\n")
    found: list[Call] = []
    for m in _CALL.finditer(text):
        title = title_at(text, m.end(), consts)
        if title is None:
            continue
        line = _line_of(line_starts, m.start())
        mods = frozenset(re.findall(r"[a-z]+", m.group(2)))
        kind = "describe" if m.group(1) == "describe" else "test"
        found.append(Call(kind, title, line, _indent(lines[line]), mods))
    for m in _EACH.finditer(text):
        titles = each_titles(text, m.end() - 1, consts)
        if titles is None:
            continue
        line = _line_of(line_starts, m.start())
        kind = "describe" if m.group(1) == "describe" else "test"
        mods = frozenset({"each"})
        found.extend(Call(kind, t, line, _indent(lines[line]), mods) for t in titles)
    found.sort(key=lambda c: c.line)
    return found


def _line_of(line_starts: Sequence[int], offset: int) -> int:
    lo, hi = 0, len(line_starts) - 1
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if line_starts[mid] <= offset:
            lo = mid
        else:
            hi = mid - 1
    return lo


def _block_end(lines: Sequence[str], start: int, indent: int) -> int:
    """The line closing the block opened at `start`: the next non-blank one indented no further."""
    for k in range(start + 1, len(lines)):
        if lines[k].strip() and _indent(lines[k]) <= indent:
            return k
    return len(lines)


def find_test(text: str, describe: Sequence[str], it: str) -> bool:
    """Whether the file holds an `it` or `test` titled `it` inside describes titled `describe`."""
    lines = text.split("\n")
    found = calls(text)

    def search(depth: int, lo: int, hi: int) -> bool:
        for c in found:
            if not lo <= c.line < hi or c.modifiers & NO_EVIDENCE:
                continue
            if depth == len(describe):
                if c.kind == "test" and c.title == it:
                    return True
            elif (
                c.kind == "describe"
                and c.title == describe[depth]
                and search(depth + 1, c.line + 1, _block_end(lines, c.line, c.indent))
            ):
                return True
        return False

    return search(0, 0, len(lines))


# The crosswalk.


class ConfigError(ValueError):
    pass


def _texts(value: Any) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [t for v in value for t in _texts(v)]
    if isinstance(value, dict):
        return [t for v in value.values() for t in _texts(v)]
    return []


def validate(config: Mapping[str, Any]) -> None:
    """Refuse a config the crosswalk cannot stand behind; the reasons name the row."""
    obligations = config.get("obligations")
    claims = config.get("claims")
    sources = config.get("sources")
    if not isinstance(obligations, list) or not isinstance(claims, list) or not claims:
        raise ConfigError("the config needs a list of obligations and a non-empty list of claims")
    if not isinstance(sources, dict):
        raise ConfigError("the config needs a sources object naming each instrument's primary text")
    oids: set[str] = set()
    for ob in obligations:
        oid = ob.get("id")
        if not isinstance(oid, str) or oid in oids:
            raise ConfigError(f"obligation {oid!r}: a missing or repeated id")
        oids.add(oid)
        if ob.get("instrument") not in sources:
            raise ConfigError(
                f"obligation {oid}: instrument {ob.get('instrument')!r} has no source"
            )
        if not isinstance(ob.get("article"), str) or not ob["article"]:
            raise ConfigError(f"obligation {oid}: an article is required")
        if not isinstance(ob.get("paragraph"), str) or not ob["paragraph"]:
            raise ConfigError(f"obligation {oid}: a paragraph is required")
        if not isinstance(ob.get("quote"), str) or not ob["quote"].strip():
            raise ConfigError(f"obligation {oid}: a quote from the primary text is required")
    cids: set[str] = set()
    for claim in claims:
        cid = claim.get("id")
        if not isinstance(cid, str) or cid in cids:
            raise ConfigError(f"claim {cid!r}: a missing or repeated id")
        cids.add(cid)
        for key in ("claim", "source"):
            if not isinstance(claim.get(key), str) or not claim[key].strip():
                raise ConfigError(f"claim {cid}: {key} is required")
        tests = claim.get("tests")
        if not isinstance(tests, list):
            raise ConfigError(f"claim {cid}: tests is a list, empty when no test proves it")
        for t in tests:
            if not isinstance(t.get("file"), str) or not isinstance(t.get("it"), str):
                raise ConfigError(f"claim {cid}: each test names a file and an it title")
            if not isinstance(t.get("describe"), list) or not all(
                isinstance(d, str) for d in t["describe"]
            ):
                raise ConfigError(f"claim {cid}: a test's describe is a list of titles")
        if not tests and not str(claim.get("gap", "")).strip():
            raise ConfigError(f"claim {cid}: a claim with no test says why in gap")
        if tests and claim.get("gap"):
            raise ConfigError(f"claim {cid}: gap is only for a claim with no test")
        links = claim.get("obligations")
        unmapped = str(claim.get("unmapped", "")).strip()
        if not isinstance(links, list) or (not links and not unmapped):
            raise ConfigError(
                f"claim {cid}: name at least one obligation it bears on, "
                f"or say in unmapped why none is cited"
            )
        if links and unmapped:
            raise ConfigError(f"claim {cid}: unmapped is only for a claim citing no obligation")
        for link in links:
            if link.get("id") not in oids:
                raise ConfigError(f"claim {cid}: unknown obligation {link.get('id')!r}")
            if link.get("relation") != RELATION:
                raise ConfigError(
                    f"claim {cid}: the relation to {link['id']} is {RELATION!r}, never another"
                )
            if not isinstance(link.get("why"), str) or not link["why"].strip():
                raise ConfigError(f"claim {cid}: say why it bears on {link['id']}")
    for row in [*claims, *obligations]:
        for text in _texts({k: v for k, v in row.items() if k != "quote"}):
            low = text.lower()
            for word in FORBIDDEN_WORDS:
                if word in low:
                    raise ConfigError(
                        f"row {row.get('id')}: {word.strip()!r} reads as a compliance claim; "
                        f"a row bears on an obligation, never meets it"
                    )


def test_ref(t: Mapping[str, Any]) -> str:
    return " > ".join([t["file"], *t["describe"], t["it"]])


def build(root: Path, config: Mapping[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """The crosswalk result and the named tests that do not exist under `root`."""
    validate(config)
    missing: list[str] = []
    texts: dict[str, str | None] = {}
    obligations = {ob["id"]: ob for ob in config["obligations"]}
    rows: list[dict[str, Any]] = []
    for claim in config["claims"]:
        tests = []
        for t in claim["tests"]:
            if t["file"] not in texts:
                path = root / t["file"]
                texts[t["file"]] = path.read_text(encoding="utf-8") if path.is_file() else None
            text = texts[t["file"]]
            if text is None:
                missing.append(f"{claim['id']}: no file {t['file']}")
            elif not find_test(text, t["describe"], t["it"]):
                missing.append(f"{claim['id']}: no test {test_ref(t)}")
            tests.append({"file": t["file"], "describe": t["describe"], "it": t["it"]})
        rows.append(
            {
                "id": claim["id"],
                "claim": claim["claim"],
                "source": claim["source"],
                "invariant": claim.get("invariant"),
                "status": "evidenced" if tests else "not evidenced",
                "tests": tests,
                "gap": claim.get("gap"),
                "limits": claim.get("limits"),
                "unmapped": claim.get("unmapped"),
                "obligations": [
                    {"id": link["id"], "relation": link["relation"], "why": link["why"]}
                    for link in claim["obligations"]
                ],
            }
        )
    by_obligation: dict[str, list[str]] = {oid: [] for oid in obligations}
    for row in rows:
        for link in row["obligations"]:
            by_obligation[link["id"]].append(row["id"])
    result = {
        "name": config.get("name", "crosswalk"),
        "card": "R4",
        "statement": config["statement"],
        "relation": RELATION,
        "sources": config["sources"],
        "obligations": [
            {
                **{k: ob.get(k) for k in ("id", "instrument", "article", "paragraph", "point")},
                "heading": ob.get("heading"),
                "quote": ob["quote"],
                "claims": by_obligation[ob["id"]],
            }
            for ob in config["obligations"]
        ],
        "claims": rows,
        "summary": {
            "claims": len(rows),
            "evidenced": sum(r["status"] == "evidenced" for r in rows),
            "not_evidenced": [r["id"] for r in rows if r["status"] == "not evidenced"],
            "tests": sum(len(r["tests"]) for r in rows),
            "test_files": len({t["file"] for r in rows for t in r["tests"]}),
            "obligations": len(obligations),
            "obligations_without_claim": [o for o, c in by_obligation.items() if not c],
            "claims_unmapped": [r["id"] for r in rows if not r["obligations"]],
        },
    }
    return result, missing


# The thesis table.


def cite(ob: Mapping[str, Any], sources: Mapping[str, Any]) -> str:
    short = sources[ob["instrument"]]["short"]
    point = "".join(f"({p})" for p in ob["point"].split(".")) if ob.get("point") else ""
    return f"{short} Art. {ob['article']}({ob['paragraph']}){point}"


def render_table(result: Mapping[str, Any]) -> str:
    obligations = {ob["id"]: ob for ob in result["obligations"]}
    lines = [
        "| id | claim | evidence | obligations it bears on | limits |",
        "|---|---|---|---|---|",
    ]
    for row in result["claims"]:
        if row["tests"]:
            evidence = "<br>".join(
                f"`{t['file']}`: {' > '.join(t['describe'] + [t['it']])}" for t in row["tests"]
            )
        else:
            evidence = f"**not evidenced**: {row['gap']}"
        cites = "; ".join(cite(obligations[o["id"]], result["sources"]) for o in row["obligations"])
        if not cites:
            cites = f"none cited: {row['unmapped']}"
        claim = row["claim"] + (f" (invariant {row['invariant']})" if row["invariant"] else "")
        limits = _cell(row["limits"] or "")
        lines.append(
            f"| {row['id']} | {_cell(claim)} | {_cell(evidence)} | {_cell(cites)} | {limits} |"
        )
    return "\n".join(lines) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def write_table(path: Path, table: str) -> None:
    text = path.read_text(encoding="utf-8")
    start = text.find(TABLE_BEGIN)
    end = text.find(TABLE_END)
    if start < 0 or end < start:
        raise ConfigError(f"{path.name}: no crosswalk table markers")
    head = text[: start + len(TABLE_BEGIN)]
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(head + "\n\n" + table + "\n" + text[end:])


def table_in(path: Path) -> str:
    """The table between the markers of a Markdown file, as `write_table` put it there."""
    text = path.read_text(encoding="utf-8")
    start = text.find(TABLE_BEGIN)
    end = text.find(TABLE_END)
    if start < 0 or end < start:
        raise ConfigError(f"{path.name}: no crosswalk table markers")
    return text[start + len(TABLE_BEGIN) : end].strip("\n") + "\n"


# The primary legal texts.


def legal_lines(xhtml: str) -> list[str]:
    """The Official Journal XHTML as plain lines, one per paragraph or cell, whitespace folded."""
    text = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", xhtml, flags=re.S)
    text = re.sub(r"</(p|div|tr|td|h\d|li)>", "\n", text)
    text = html.unescape(re.sub(r"<[^>]+>", " ", text))
    lines = (re.sub(r"\s+", " ", ln).strip() for ln in text.splitlines())
    return [ln for ln in lines if ln]


def _fold(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u2019", "'")).strip()


def locate(lines: Sequence[str], article: str, paragraph: str, point: str | None) -> str:
    """The text of one article's paragraph (and point), from the plain lines of the act."""
    head = f"Article {article}"
    try:
        start = lines.index(head)
    except ValueError as e:
        raise ConfigError(f"no {head}") from e
    end = next(
        (k for k in range(start + 1, len(lines)) if re.fullmatch(r"Article \d+[a-z]?", lines[k])),
        len(lines),
    )
    body = list(lines[start + 1 : end])
    marks = [k for k, ln in enumerate(body) if re.match(rf"{re.escape(paragraph)}\. ", ln)]
    if not marks:
        raise ConfigError(f"{head} has no paragraph {paragraph}")
    p0 = marks[0]
    p1 = next(
        (k for k in range(p0 + 1, len(body)) if re.match(r"\d+\. ", body[k])),
        len(body),
    )
    para = body[p0:p1]
    if point is None:
        return " ".join(para)
    letter, _, roman = point.partition(".")
    try:
        q0 = para.index(f"({letter})")
    except ValueError as e:
        raise ConfigError(f"{head}({paragraph}) has no point ({letter})") from e
    after = f"({chr(ord(letter) + 1)})"
    q1 = next((k for k in range(q0 + 1, len(para)) if para[k] == after), len(para))
    seg = para[q0:q1]
    if not roman:
        return " ".join(seg)
    try:
        r0 = seg.index(f"({roman})")
    except ValueError as e:
        raise ConfigError(f"{head}({paragraph})({letter}) has no point ({roman})") from e
    r1 = next(
        (k for k in range(r0 + 1, len(seg)) if re.fullmatch(r"\([ivx]+\)", seg[k])),
        len(seg),
    )
    return " ".join(seg[r0:r1])


def check_legal(config: Mapping[str, Any], folder: Path) -> list[str]:
    """Problems with the quotes: each must stand in the article, paragraph and point it cites."""
    problems: list[str] = []
    lines: dict[str, list[str]] = {}
    for key, src in config["sources"].items():
        path = folder / src["file"]
        if not path.is_file():
            problems.append(f"{key}: no {src['file']} in the legal folder")
            continue
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != src["sha256"]:
            problems.append(f"{key}: {src['file']} does not hash to the config's sha256")
            continue
        lines[key] = legal_lines(data.decode("utf-8"))
    for ob in config["obligations"]:
        if ob["instrument"] not in lines:
            continue
        try:
            text = locate(lines[ob["instrument"]], ob["article"], ob["paragraph"], ob.get("point"))
        except ConfigError as e:
            problems.append(f"{ob['id']}: {e}")
            continue
        if _fold(ob["quote"]) not in _fold(text):
            problems.append(f"{ob['id']}: the quote is not in {cite(ob, config['sources'])}")
        if ob.get("heading") and ob["heading"] not in lines[ob["instrument"]]:
            problems.append(f"{ob['id']}: no heading {ob['heading']!r}")
    return problems


def fetch_legal(config: Mapping[str, Any], folder: Path) -> None:
    """Fetch each primary text the config names from the Publications Office (data only)."""
    if os.environ.get("ENGRAM_OFFLINE") == "1":
        raise SystemExit("crosswalk: refusing to fetch the legal texts under ENGRAM_OFFLINE=1")
    folder.mkdir(parents=True, exist_ok=True)
    for src in config["sources"].values():
        request = urllib.request.Request(
            src["url"],
            headers={"Accept": "application/xhtml+xml", "Accept-Language": "eng"},
        )
        with urllib.request.urlopen(request, timeout=120) as response:
            (folder / src["file"]).write_bytes(response.read())


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--root", type=Path, default=REPO)
    parser.add_argument(
        "--table", type=Path, help="a Markdown file whose crosswalk block to rewrite"
    )
    parser.add_argument("--legal", type=Path, help="a folder holding the primary legal texts")
    parser.add_argument("--fetch", action="store_true", help="fetch the legal texts into --legal")
    args = parser.parse_args(argv)
    config = load_config(args.config)
    try:
        result, missing = build(args.root.resolve(), config)
    except ConfigError as e:
        print(f"crosswalk: {e}", file=sys.stderr)
        return 2
    if missing:
        for m in missing:
            print(f"crosswalk: missing {m}", file=sys.stderr)
        print(
            f"crosswalk: {len(missing)} named tests do not exist; nothing written", file=sys.stderr
        )
        return 1
    if args.legal is not None:
        if args.fetch:
            fetch_legal(config, args.legal)
        problems = check_legal(config, args.legal)
        for p in problems:
            print(f"crosswalk: legal {p}", file=sys.stderr)
        if problems:
            return 1
        print(f"crosswalk: {len(config['obligations'])} quotes stand in the primary texts")
    write_result(args.out, result)
    if args.table is not None:
        write_table(args.table, render_table(result))
    s = result["summary"]
    print(
        f"crosswalk: {s['claims']} claims, {s['evidenced']} evidenced by {s['tests']} tests "
        f"in {s['test_files']} files, {len(s['not_evidenced'])} not evidenced, "
        f"{s['obligations']} obligations"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
