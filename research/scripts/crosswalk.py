"""The crosswalk (card R4): governance claims, the tests that prove them, the obligations.

Usage:
    uv run python research/scripts/crosswalk.py \\
        --config research/configs/crosswalk.json --out research/results/h1-crosswalk.json \\
        [--table docs/compliance/README.md] [--legal .engram/upstream/legal [--fetch]]

The config holds one row per claim Engram makes about governance (from
AGENTS.md, docs/architecture.md, the invariants, ADRs 0004 to 0011, 0014, 0021
and 0025, and docs/dogfood.md), the tests that prove it, named by test file
and by the titles of its `describe` blocks and its `it` or `test` call, and
the obligations of the EU AI Act (Regulation (EU) 2024/1689) or the GDPR
(Regulation (EU) 2016/679) it bears on, each cited by article, paragraph and
point. A claim with no test is marked not evidenced; it is never given one.

The check reads the test files as text, never running vitest (`scan`):
comments, string bodies and regular expression literals are blanked, so a
call written in a comment or a string is not a call, and the brackets are
paired. A test is evidence when an `it` or `test` call carries the named
title, the named describes enclose it in that order, nothing around it is
skipped (`.skip`, `.todo`, `.fails`, `.skipIf`, `.runIf`, an options object's
`skip`, a context's `skip()`), and every bracket around it is a describe call
or the function body passed to one; a test inside any other block counts
only when its row says why it runs (`enclosed`). Titles are resolved as
vitest names them, `.each` and `.for` tables included (`format_title`).
docs/compliance/README.md ("Method") states the rules exactly. When any
named test is not evidence, the script prints each one with its status and
exits 1 without writing.

`--table` rewrites the block between the crosswalk markers of a Markdown file
with the thesis table, after checking the file's other text for wording that
reads as a compliance claim. `--legal DIR` checks every quoted obligation against
the Official Journal texts in DIR (the files the config's `sources` name,
fetched with `--fetch` from the Publications Office, data only, refused under
ENGRAM_OFFLINE=1): each file's sha256 must be the config's, and each quote
must stand, verbatim up to whitespace, in the cited article, paragraph and
point. The result carries no time and no absolute path.
"""

