"""Shared helpers for research/scripts: configs, byte-stable results, node, pinned data.

A results file (AGENTS.md rule 9) is regenerated by `research/scripts/<name>.py
--config research/configs/<name>.json --out research/results/<name>.json` and
must be byte-stable: `write_result` sorts keys, rounds floats to six decimals,
writes UTF-8 with "\\n" line endings, and the caller puts no time and no
absolute path in it.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import urllib.request
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
DECIMALS = 6


def load_config(path: Path) -> dict[str, Any]:
    config = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise ValueError(f"{path}: a config is a JSON object")
    return config


def _rounded(value: Any) -> Any:
    if isinstance(value, float):
        rounded = round(value, DECIMALS)
        return 0.0 if rounded == 0.0 else rounded
    if isinstance(value, dict):
        return {str(k): _rounded(v) for k, v in value.items()}
    if isinstance(value, list | tuple):
        return [_rounded(v) for v in value]
    return value


def dumps_result(result: Any) -> str:
    """The bytes of a results file, as text: sorted keys, rounded floats, a final newline."""
    return json.dumps(_rounded(result), sort_keys=True, indent=2, ensure_ascii=False) + "\n"


def write_result(path: Path, result: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(dumps_result(result))


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run_node(args: Sequence[str]) -> None:
    """Run a TypeScript entry point with node from the repository root; fail on a non-zero exit."""
    subprocess.run(["node", *args], cwd=REPO, check=True)


def line_hashes(path: Path) -> list[str]:
    """The sha256 of every line as the vendoring wrote them, one final newline dropped."""
    lines = path.read_text(encoding="utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [hashlib.sha256(line.encode("utf-8")).hexdigest() for line in lines]


GATEMEM_DOMAINS = ("education", "household", "medical", "office")


def ensure_pinned_gatemem(data: Path, manifest_path: Path, *, fetch: bool) -> str:
    """Check GateMem's eight data files against the pinned sha256; fetch missing ones first.

    As packages/bench/scripts/dry-run-gatemem.ts --fetch does: the files come
    from the pinned commit over HTTPS (data only, never a model). Refuses to
    fetch under ENGRAM_OFFLINE=1. Returns the pinned commit.
    """
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    commit = str(manifest["source"]["commit"])
    raw = str(manifest["source"]["repository"]).replace(
        "https://github.com/", "https://raw.githubusercontent.com/"
    )
    for domain in GATEMEM_DOMAINS:
        for name in ("episodes.jsonl", "checkpoints.jsonl"):
            expected = manifest["upstream_sha256"][f"bench/data/{domain}/{name}"]
            target = data / domain / name
            if not target.exists():
                if not fetch:
                    raise FileNotFoundError(f"{target} is missing; set fetch in the config")
                if os.environ.get("ENGRAM_OFFLINE") == "1":
                    raise RuntimeError(
                        f"{target} is missing and ENGRAM_OFFLINE=1 forbids the fetch"
                    )
                url = f"{raw}/{commit}/bench/data/{domain}/{name}"
                with urllib.request.urlopen(url) as response:
                    body = response.read()
                if hashlib.sha256(body).hexdigest() != expected:
                    raise ValueError(f"fetch {url}: sha256 differs from the manifest")
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(body)
            if sha256_file(target) != expected:
                raise ValueError(f"{target}: sha256 differs from the pinned manifest")
    return commit
