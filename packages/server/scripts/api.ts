// Writes the HTTP contract and its generated clients (cards E8.1 and E8.3, ADR
// 0027 decisions 1 and 2). Run by `make api`; `make api-check` fails when what
// it writes differs from what is committed. Every file it writes is generated
// here and never edited by hand:
//
//   sdk/openapi.json               the OpenAPI 3.1 document, from the route table
//   sdk/ts/package.json            the client package (@engram/sdk), a workspace package
//   sdk/ts/src/schema.ts           types, by openapi-typescript
//   sdk/ts/src/index.ts            the client factory over openapi-fetch
//   packages/ui/src/api/schema.ts  the same types for the inspector
//   packages/ui/src/api/index.ts   the same factory for the inspector
//
// openapi-typescript builds its output with the TypeScript compiler API, which
// the repository's native TypeScript 7 does not ship; it runs on the
// TypeScript 5 pinned beside it in packages/server (docs/deps.md).
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString, UNKNOWN } from "openapi-typescript";
import { openApiDocument } from "../src/openapi.ts";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const HEADER =
  "// Generated by `make api` (packages/server/scripts/api.ts) from sdk/openapi.json. Do not edit.\n";

function write(path: string, text: string): void {
  const full = join(repo, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, text);
}

/**
 * Empties a generated folder, so a file the generator no longer writes does
 * not linger; `keep` names what is not generated (pnpm's node_modules).
 */
function reset(dir: string, keep: readonly string[] = []): void {
  const full = join(repo, dir);
  mkdirSync(full, { recursive: true });
  for (const entry of readdirSync(full))
    if (!keep.includes(entry)) rmSync(join(full, entry), { recursive: true });
}

const doc = openApiDocument();
write("sdk/openapi.json", `${JSON.stringify(doc, null, 2)}\n`);

// JsonValue is recursive; as a property of the components interface it would
// name itself (TS2502), so its type is `unknown`: any JSON value.
const ast = await openapiTS(doc as never, {
  silent: true,
  transform: (_schema, options) =>
    options.path === "#/components/schemas/JsonValue" ? UNKNOWN : undefined,
});
const schemaTs = `${HEADER}${astToString(ast)}`;
const names = Object.keys((doc.components as { schemas: Record<string, unknown> }).schemas);

const indexTs = `${HEADER}// The Engram HTTP client (card E8.3): openapi-fetch over the generated types.
// Bind \`fetch\` to an app's fetch (createApp(...).fetch) to call a workspace in
// process, or give a server's base URL to call it over HTTP.
import createClient, { type Client } from "openapi-fetch";
import type { components, paths } from "./schema.ts";

export type { components, operations, paths } from "./schema.ts";

type Schemas = components["schemas"];
${names.map((n) => `export type ${n} = Schemas["${n}"];`).join("\n")}

export type EngramClient = Client<paths>;

export interface EngramClientOptions {
  /** The server's base URL, such as http://127.0.0.1:7313. */
  baseUrl: string;
  /** The fetch every call goes through; the global fetch when absent. */
  fetch?: (request: Request) => Promise<Response>;
}

export function createEngramClient(options: EngramClientOptions): EngramClient {
  return createClient<paths>({
    baseUrl: options.baseUrl,
    ...(options.fetch ? { fetch: options.fetch } : {}),
  });
}
`;

const packageJson = {
  name: "@engram/sdk",
  version: "0.0.0",
  private: true,
  description: "Generated by `make api` from sdk/openapi.json. Do not edit.",
  type: "module",
  exports: { ".": "./src/index.ts" },
  dependencies: { "openapi-fetch": "0.17.0" },
};

reset("sdk/ts", ["node_modules"]);
write("sdk/ts/package.json", `${JSON.stringify(packageJson, null, 2)}\n`);
write("sdk/ts/src/schema.ts", schemaTs);
write("sdk/ts/src/index.ts", indexTs);
reset("packages/ui/src/api");
write("packages/ui/src/api/schema.ts", schemaTs);
write("packages/ui/src/api/index.ts", indexTs);
